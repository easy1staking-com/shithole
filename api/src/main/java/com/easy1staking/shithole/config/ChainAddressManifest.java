import com.easy1staking.shithole.blueprint.generated.listing.ListingSpendValidator;
import com.easy1staking.shithole.blueprint.generated.marketplace.MarketplaceSpendValidator;
import com.easy1staking.shithole.blueprint.generated.wantedlisting.WantedListingSpendValidator;
import com.easy1staking.shithole.entity.ConfigEntity;
